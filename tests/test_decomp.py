def test_tileset_view_roundtrip(proj, tmp_path):
    ts = proj.get("data/tilesets/primary/general@tileset")
    tiles_png = proj.root / ts.meta["tiles_file"]
    before = np.array(Image.open(tiles_png))
    proj.render_image(ts).save(tmp_path / "v.png")
    proj.import_image(ts, tmp_path / "v.png")
    assert np.array_equal(np.array(Image.open(tiles_png)) & 15, before & 15)
    idx, _plte, _ = proj.view(ts)
    idx = idx.copy()
    idx[0:8, 0:8] = (idx[0, 0] & 0xF0) | 9
    proj.write_view(ts, idx)
    after = np.array(Image.open(tiles_png))
    assert (after[0:8, 0:8] == 9).all() and np.array_equal(after[8:], before[8:])


def test_bg_view_retile(proj):
    bg = proj.get("graphics/battle_anims/backgrounds/dark@bg")
    idx, _plte, _ = proj.view(bg)
    assert idx.shape == (256, 256)
    new = np.full_like(idx, 2)
    new[0:16, 0:40] = 5
    proj.write_view(bg, new)
    again, _, _ = proj.view(bg)
    assert np.array_equal(again, new)
    assert {s["id"] for s in proj.status()} == {"graphics/battle_anims/backgrounds/dark.png",
                                                 "graphics/battle_anims/backgrounds/dark.bin"}
    proj.revert(bg)
    assert proj.status() == []


