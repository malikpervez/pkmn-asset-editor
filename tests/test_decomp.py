def test_cli_and_mcp(repo, tmp_path, capsys):
    root = str(repo)
    assert main(["list", "-p", root, "-c", "pokemon"]) == 0
    assert main(["describe", "-p", root, "graphics/pokemon/bulbasaur/back"]) == 0
    assert "normal.pal" in capsys.readouterr().out
    assert main(["check", "-p", root, "--all"]) == 0
    assert main(["sheet", "-p", root, "graphics/pokemon", "-o", str(tmp_path / "s.png")]) == 0
    assert main(["render", "-p", root, "graphics/pokemon/pikachu/anim_front.png", "--palette",
                 "graphics/pokemon/pikachu/shiny.pal", "-o", str(tmp_path / "shiny.png")]) == 0
    srv = Server(DecompProject(repo))
    call = lambda name, **a: srv.handle({"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                                         "params": {"name": name, "arguments": a}})["result"]
    px = json.loads(call("get_pixels", id="graphics/items/icons/potion.png")["content"][0]["text"])
    assert px["w"] == 24
    assert not call("paint_pixels", id="graphics/items/icons/potion.png", rects=[{"x": 0, "y": 0, "w": 4, "h": 4, "index": 3}])["isError"]
    ts = json.loads(call("get_pixels", id="data/tilesets/primary/general@tileset", w=8, h=1)["content"][0]["text"])
    assert ts["chars_per_pixel"] == 2
    assert call("view_asset", id="data/tilesets/secondary/town@tileset")["content"][0]["type"] == "image"
    assert not call("set_palette", id="graphics/items/icon_palettes/super_potion.pal",
                    colors=["#000000"] * 16)["isError"]
    rep = json.loads(call("validate")["content"][0]["text"])
    assert rep["ok"]
    assert main(["revert", "-p", root, "--all"]) == 0
    assert DecompProject(repo).status() == []
