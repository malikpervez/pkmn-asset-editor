"""Read-only renders that help people and AI agents see what they are editing."""

from __future__ import annotations

from typing import TYPE_CHECKING, Iterable

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from . import formats
from .gfx import decode_tiles, pad_palette

if TYPE_CHECKING:
    from .project import Project


def metatile_sheet(proj: "Project", asset, palettes=None) -> Image.Image | None:
    meta = asset.meta
    count = meta.get("metatile_count") or 0
    if not count:
        return None
    info = proj.rom.info
    npt = info.num_primary_tiles
    palettes = palettes or proj.current_palettes()
    own = decode_tiles(proj.raw(asset.blobs["tiles"]))
    if meta.get("secondary"):
        prim = proj.assets.get(f"{meta['primary']}/tiles") if meta.get("primary") else None
        ptiles = decode_tiles(proj.raw(prim.blobs["tiles"])) if prim else np.zeros((0, 8, 8), np.uint8)
        pad = np.zeros((max(0, npt - len(ptiles)), 8, 8), np.uint8)
        tiles = np.concatenate([ptiles[:npt], pad, own])
    else:
        tiles = own
    plte = np.array(pad_palette(formats.image_palette(asset, palettes), 256), dtype=np.uint8)
    per_row = 8
    rows = -(-count // per_row)
    out = np.zeros((rows * 16, per_row * 16, 3), dtype=np.uint8)
    rom = proj.rom
    base = meta["metatiles_offset"]
    blank = np.zeros((8, 8), np.uint8)
    for m in range(count):
        mx, my = (m % per_row) * 16, (m // per_row) * 16
        for layer in (0, 1):
            for q in range(4):
                v = rom.u16(base + m * 16 + (layer * 4 + q) * 2)
                t, hf, vf, bank = v & 0x3FF, (v >> 10) & 1, (v >> 11) & 1, v >> 12
                px = tiles[t] if t < len(tiles) else blank
                if hf:
                    px = px[:, ::-1]
                if vf:
                    px = px[::-1, :]
                x, y = mx + (q % 2) * 8, my + (q // 2) * 8
                colors = plte[bank * 16 + px]
                if layer == 0:
                    out[y:y + 8, x:x + 8] = colors
                else:
                    mask = px != 0
                    out[y:y + 8, x:x + 8][mask] = colors[mask]
    return Image.fromarray(out, "RGB")


def write_previews(proj: "Project") -> None:
    palettes = proj.current_palettes()
    for a in proj.assets.values():
        if a.kind == "tileset":
            img = metatile_sheet(proj, a, palettes)
            if img is not None:
                path = proj.root / "previews" / (a.id.removesuffix("/tiles") + "_metatiles.png")
                path.parent.mkdir(parents=True, exist_ok=True)
                img.save(path)


def contact_sheet(proj: "Project", assets: Iterable, scale: int = 2, max_width: int = 1600,
                  labels: bool = True) -> Image.Image:
    """Lay many assets out on one image with their ids – handy for multimodal models."""
    font = ImageFont.load_default()
    items = []
    for a in assets:
        try:
            im = proj.render_image(a)
        except Exception:  # noqa: BLE001 – a broken file should not stop the overview
            continue
        if scale != 1:
            im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        items.append((a.id, im))
    if not items:
        return Image.new("RGBA", (1, 1))
    pad, label_h = 8, 12 if labels else 0
    # shelf packing: each item keeps its own size, rows wrap at max_width
    placed, x, y, row_h, width = [], pad, pad, 0, 0
    for aid, im in items:
        w = max(im.width, 90 if labels else 0)
        if x + w > max_width and x > pad:
            x, y, row_h = pad, y + row_h + pad, 0
        placed.append((aid, im, x, y))
        x += w + pad
        width = max(width, x)
        row_h = max(row_h, im.height + label_h)
    sheet = Image.new("RGBA", (width, y + row_h + pad), (40, 40, 48, 255))
    draw = ImageDraw.Draw(sheet)
    for aid, im, x, y in placed:
        sheet.paste(Image.new("RGBA", im.size, (70, 70, 80, 255)), (x, y + label_h))
        sheet.alpha_composite(im, (x, y + label_h))
        if labels:
            short = aid.split("/", 1)[-1]
            draw.text((x, y), short[-max(15, im.width // 6):], fill=(230, 230, 230, 255), font=font)
    return sheet


def agents_guide(proj: "Project") -> str:
    game = proj.config["game"]
    counts = proj.summary()
    lines = "\n".join(f"| `{k}` | {v} |" for k, v in sorted(counts.items()))
    return f"""# Asset project: {game['name']} ({game['code']})

This folder was generated by **pkmn-asset-editor** (`pae`). Every graphic that
was found in the ROM is a normal file under `graphics/`. Edit the files, then
run `pae build` to write a new ROM (plus `.ups`/`.ips` patches) into `build/`.
The original ROM (`original.gba`) is never modified; every build starts from it.

| category | assets |
|---|---|
{lines}

## Layout

```
graphics/pokemon/NNN_name/front.png      battle sprite (front; Emerald: 2 animation frames stacked)
graphics/pokemon/NNN_name/back.png       battle sprite (back)
graphics/pokemon/NNN_name/icon.png       party/PC icon (2 frames, 32x32 each, stacked)
graphics/pokemon/NNN_name/normal.pal     normal palette (shared by front + back)
graphics/pokemon/NNN_name/shiny.pal      shiny palette
graphics/pokemon/_icon_palettes/N.pal    the shared icon palettes
graphics/trainers/NNN/front.png, palette.pal
graphics/items/NNN_name/icon.png, palette.pal
graphics/battle_anims/sprites/TAG/gfx.png, palette.pal   move-animation sprites (frames stacked vertically)
graphics/battle_anims/backgrounds/NN/bg.png, palette.pal  move-animation backgrounds
graphics/battle_backgrounds/NN/scene.png, entry.png, palette.pal
graphics/overworld/NNN/sprite.png        overworld (walking) sprites, frames left-to-right
graphics/overworld/palettes/TAG.pal
graphics/tilesets/primary_NN/tiles.png   map tiles (+ palettes.pal with 16 palettes x 16 colours)
graphics/tilesets/secondary_NN/...
graphics/unknown/OFFSET.png              other compressed graphics that were found but not identified
previews/                                read-only renders (metatiles); never read back
manifest.json                            machine-readable description of every asset
```

`manifest.json` lists each asset with `id`, `kind`, `file`, `label`, `layout`
(frame size in 8x8 tiles), `palettes` (which palette files colour it) and
`aliases` (other table entries that point at the same data).

## Rules that keep the ROM valid

1. **Keep the image size.** Sprites and tiles cannot change dimensions
   (`pae import --resize` scales new artwork for you).
2. **16 colours per palette, index 0 is transparent.** Sprite PNGs are 4-bit
   indexed. Keep them indexed with the same palette order when editing, *or*
   save any RGBA PNG and `pae` will map colours to the nearest palette entry
   (`pae import --new-palette` builds a fresh palette from the artwork).
3. **Colours are 15-bit.** Each channel is rounded to a multiple of 8.
4. **Palettes:** edit the `.pal` file (JASC-PAL text) *or* the PNG's palette.
   If both are edited, the `.pal` file wins. Palettes shared by several images
   (front/back, icons, tilesets) change all of them.
5. **Tilesets & backgrounds** are 8-bit indexed PNGs where pixel value =
   `palette_bank * 16 + colour`. Only the colour part of a tileset pixel is
   stored; which palette a tile uses in-game comes from the metatiles.
   Backgrounds are rebuilt into tiles automatically (with flip de-duplication)
   but must not need more unique 8x8 tiles than the original had.
6. Data that grows after recompression is moved to free space and every
   pointer to it is updated automatically.

## Workflow for AI agents

```
pae list --project . [--category pokemon] [--json]   # find assets
pae describe <asset-id> --project .                   # constraints for one asset
pae import <asset-id> art.png --project . [--resize] [--new-palette]
pae sheet pokemon --project . -o sheet.png            # contact sheet to look at many sprites
pae status --project .                                # what changed
pae validate --project .                              # check everything before building
pae build --project .                                 # write build/rom.gba (+ patches)
pae revert <asset-id> --project .                     # undo an edit
```

There is also an MCP server (`pae mcp --project .`) exposing the same
operations as tools, and a local web editor (`pae serve --project .`).
"""
