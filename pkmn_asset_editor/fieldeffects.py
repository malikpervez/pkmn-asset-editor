"""Field-effect art for tilesets you drew yourself: the tall grass the game draws over the player's feet.

When someone walks into tall grass the game puts a small sprite over their feet (the grass in front of them) and
animates it: blades part, bits of leaf fly. That sprite is FRLG's grass in a palette shared by other effects, so on
grass you drew yourself it doesn't match. ``set_tall_grass(maps, tileset, frames, palette)`` gives a tileset its own
sprite: five 16x16 frames (as the game's: 0 standing in the grass, 1 the blades parting, 2-4 leaves flying) in one
palette of 16 colours (index 0 transparent), usually the grass tiles' own palette so the sprite blends into them.
Several kinds of tall grass in one tileset can each have their own (``by_metatile``): the grass under the player's
feet picks it, and the tileset's own is for the others.

Each tileset's sprite is recorded in ``src/data/pae_field_effects.json``; ``src/data/pae_field_effects.h`` is
generated from it, and ``FldEff_TallGrass`` in ``src/field_effect_helpers.c`` asks it for the sprite (hooked in
once): the map's primary or secondary tileset picks it, other maps keep the game's own.
"""

from __future__ import annotations

import json

import numpy as np

from .decomp import DecompError
from .gfx import rgb_to_bgr555

RECORD = "src/data/pae_field_effects.json"
HEADER = "src/data/pae_field_effects.h"
HOOK_C = "src/field_effect_helpers.c"
HOOK_FROM = "template = gFieldEffectObjectTemplatePointers[FLDEFFOBJ_TALL_GRASS];"
HOOK_TO = "template = PaeTallGrassTemplate(gFieldEffectObjectTemplatePointers[FLDEFFOBJ_TALL_GRASS], x, y);"
HOOK_OLD = "template = PaeTallGrassTemplate(gFieldEffectObjectTemplatePointers[FLDEFFOBJ_TALL_GRASS]);"
INCLUDE = '#include "data/pae_field_effects.h"'
PAL_TAG = 0x1040  # field-effect palette tags the game doesn't use; one per tileset from here
FRAMES = 5


def _tiles_4bpp(frame: np.ndarray) -> list[int]:
    """A 16x16 frame as the four 8x8 tiles of a 16x16 sprite (top left, top right, bottom left, bottom right)."""
    out: list[int] = []
    for ty in (0, 8):
        for tx in (0, 8):
            px = frame[ty:ty + 8, tx:tx + 8]
            out += list((px[:, 0::2] | (px[:, 1::2] << 4)).astype(np.uint8).tobytes())
    return out


def _check(frames) -> None:
    if len(frames) != FRAMES or any(np.asarray(f).shape != (16, 16) for f in frames):
        raise DecompError(f"the tall grass sprite has {FRAMES} frames of 16x16 pixels")
    if any(int(np.asarray(f).max()) > 15 for f in frames):
        raise DecompError("the tall grass sprite uses palette indices 0-15")


def set_tall_grass(maps, tileset: str, frames: list[np.ndarray], palette: list,
                   by_metatile: dict[int, list[np.ndarray]] | None = None) -> dict:
    """Give ``tileset`` (gTileset_X) its own tall-grass sprite: ``frames`` are five 16x16 arrays of palette indices.
    ``by_metatile``: metatile id -> frames, for grass that has a sprite of its own (the same palette)."""
    if tileset not in maps.tilesets:
        raise DecompError(f"unknown tileset {tileset}")
    _check(frames)
    for f in (by_metatile or {}).values():
        _check(f)
    hook = maps.root / HOOK_C
    if not hook.exists():
        raise DecompError(f"no {HOOK_C} in this game")
    rec_path = maps.root / RECORD
    rec = json.loads(rec_path.read_text()) if rec_path.exists() else []
    rec = [r for r in rec if r["tileset"] != tileset]
    rec.append({"tileset": tileset, "effect": "tall_grass",
                "frames": [np.asarray(f, np.uint8).tolist() for f in frames],
                "palette": [list(map(int, c[:3])) for c in (list(palette) + [(0, 0, 0)] * 16)[:16]],
                "by_metatile": {str(m): [np.asarray(f, np.uint8).tolist() for f in fr]
                                for m, fr in sorted((by_metatile or {}).items())}})
    rec.sort(key=lambda r: r["tileset"])
    maps.dp._backup(RECORD)
    rec_path.write_text(json.dumps(rec) + "\n")
    _write_header(maps, rec)
    _hook(maps)
    return {"tileset": tileset, "tag": PAL_TAG + [r["tileset"] for r in rec].index(tileset)}


def _write_header(maps, rec: list[dict]) -> None:
    out = ["// Generated by pae (`pae tileset build`, \"field_effects\") from src/data/pae_field_effects.json:",
           "// tall-grass sprites for tilesets drawn with pae. Do not edit by hand.",
           "#ifndef GUARD_PAE_FIELD_EFFECTS_H", "#define GUARD_PAE_FIELD_EFFECTS_H", "",
           "// metatile: the grass block it is for (ANY: the tileset's own, for its other tall grass)",
           "#define PAE_TALL_GRASS_ANY 0xFFFF", "",
           "struct PaeTallGrass", "{", "    const struct Tileset *tileset;", "    u16 metatile;",
           "    const struct SpriteFrameImage *images;", "    const struct SpritePalette *palette;", "};", ""]
    entries = []
    for i, r in enumerate(rec):
        out.append(f"static const u16 sPaeTallGrassPal_{i}[16] = {{ "
                   + ", ".join(f"0x{rgb_to_bgr555(tuple(c)):04X}" for c in r["palette"]) + " };")
        out.append(f"static const struct SpritePalette sPaeTallGrassPalette_{i} = "
                   f"{{ sPaeTallGrassPal_{i}, 0x{PAL_TAG + i:04X} }};")
        sprites = [(int(m), fr, f"{i}_{m}") for m, fr in r.get("by_metatile", {}).items()]
        sprites.append((None, r["frames"], f"{i}"))  # the tileset's own last: specific grass is found first
        for mid, fr, name in sprites:
            data = [b for f in fr for b in _tiles_4bpp(np.array(f, np.uint8))]
            out.append(f"static const u8 ALIGNED(4) sPaeTallGrassPic_{name}[{len(data)}] = {{ "
                       + ", ".join(f"0x{v:02X}" for v in data) + " };")
            out.append(f"static const struct SpriteFrameImage sPaeTallGrassFrames_{name}[] = {{")
            out += [f"    overworld_frame(sPaeTallGrassPic_{name}, 2, 2, {k})," for k in range(FRAMES)]
            out.append("};")
            entries.append(f"    {{ &{r['tileset']}, {'PAE_TALL_GRASS_ANY' if mid is None else mid}, "
                           f"sPaeTallGrassFrames_{name}, &sPaeTallGrassPalette_{i} }},")
    out.append("")
    if entries:
        out += ["static const struct PaeTallGrass sPaeTallGrass[] =", "{"] + entries + ["};", ""]
    out += ["// The tall-grass sprite for the map's tilesets: the game's own unless pae drew one for them.",
            "// (x, y): where it grows, in map coordinates (the grass block there may have a sprite of its own)",
            "static const struct SpriteTemplate *PaeTallGrassTemplate(const struct SpriteTemplate *template, s16 x, s16 y)",
            "{"]
    if entries:
        out += ["    static struct SpriteTemplate sTemplate;",
                "    const struct MapLayout *layout = gMapHeader.mapLayout;",
                "    u32 metatile = MapGridGetMetatileIdAt(x, y);",
                "    u32 i;", "",
                "    for (i = 0; i < ARRAY_COUNT(sPaeTallGrass); i++)",
                "    {",
                ("        if ((layout->primaryTileset == sPaeTallGrass[i].tileset"
                 " || layout->secondaryTileset == sPaeTallGrass[i].tileset)"),
                ("         && (sPaeTallGrass[i].metatile == PAE_TALL_GRASS_ANY"
                 " || sPaeTallGrass[i].metatile == metatile))"),
                "        {",
                "            u32 slot = LoadSpritePalette(sPaeTallGrass[i].palette);",
                "            SetPaletteColorMapType(slot + 16, COLOR_MAP_DARK_CONTRAST);",
                "            UpdateSpritePaletteWithWeather(slot, TRUE);",
                "            sTemplate = *template;",
                "            sTemplate.images = sPaeTallGrass[i].images;",
                "            sTemplate.paletteTag = sPaeTallGrass[i].palette->tag;",
                "            return &sTemplate;",
                "        }",
                "    }"]
    out += ["    return template;", "}", "", "#endif // GUARD_PAE_FIELD_EFFECTS_H", ""]
    maps.dp._backup(HEADER)
    (maps.root / HEADER).write_text("\n".join(out))


def _hook(maps) -> None:
    """Include the header in field_effect_helpers.c and have FldEff_TallGrass ask it for the sprite (once)."""
    path = maps.root / HOOK_C
    text = path.read_text()
    if HOOK_TO in text and INCLUDE in text:
        return
    if HOOK_OLD in text:  # hooked by an older pae, without the place: give it the place
        maps.dp._backup(HOOK_C)
        path.write_text(text.replace(HOOK_OLD, HOOK_TO, 1))
        return
    if HOOK_FROM not in text:
        raise DecompError(f"can't find FldEff_TallGrass's sprite template in {HOOK_C}")
    lines = text.split("\n")
    last_include = max(i for i, ln in enumerate(lines) if ln.startswith("#include"))
    if INCLUDE not in text:
        lines.insert(last_include + 1, INCLUDE)
    text = "\n".join(lines).replace(HOOK_FROM, HOOK_TO, 1)
    maps.dp._backup(HOOK_C)
    path.write_text(text)
